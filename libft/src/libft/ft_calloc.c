#include "libft.h"

void	*ft_calloc(size_t nmemb, size_t size)
{
	void	*mem;

	if (nmemb == 0 || size == 0)
	{
		nmemb = 1;
		size = 1;
	}
	mem = ft_malloc(nmemb * size, 0);
	if (mem)
		ft_bzero(mem, nmemb * size);
	return (mem);
}
